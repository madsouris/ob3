import { ArrowLeftIcon, PrinterIcon } from 'lucide-react';
import { BusinessLogo } from '@/components/business-logo';
import { Button } from '@/components/ui/button';
import { Markdown } from '@/components/markdown';
import { PaymentBlock } from '@/components/payment-block';
import { formatDate } from '@/lib/format';
import { navigate } from '@/lib/router';
import { templateVariablesFor } from '@/lib/document-variables';
import { renderTemplate } from '@/lib/template';
import { recordTitle, useWorkspace } from '@/lib/workspace';

export interface DocumentPrintProps {
  readonly documentId: string;
}

/** A4 print view for a document, with template variables resolved. */
export const DocumentPrint = ({ documentId }: DocumentPrintProps) => {
  const { records, config, loading } = useWorkspace();

  const document = records.document.find((record) => record.id === documentId) ?? null;
  const back = (): void => navigate(`documents/${documentId}`);

  if (document === null) {
    return (
      <div className="print-shell flex min-h-dvh flex-col items-center justify-center gap-4 p-8">
        {loading ? (
          <p className="text-sm text-muted-foreground">Loading the document…</p>
        ) : (
          <>
            <p className="text-sm text-muted-foreground">This document was not found.</p>
            <Button variant="outline" size="sm" onClick={() => navigate('documents')}>
              Back to documents
            </Button>
          </>
        )}
      </div>
    );
  }

  const business = config?.business;
  const businessName =
    business?.name === undefined || business.name === '' ? 'Your business' : business.name;
  const client =
    document.scope !== 'client' || document.client_id === ''
      ? null
      : (records.contact.find((contact) => contact.id === document.client_id) ?? null);
  const variables = templateVariablesFor({ config, client });
  const content = renderTemplate(document.body, variables);

  return (
    <div className="print-shell flex min-h-dvh flex-col bg-muted/40">
      <div className="no-print mx-auto flex w-full max-w-4xl items-center justify-between gap-3 px-4 py-4">
        <Button variant="ghost" size="sm" onClick={back}>
          <ArrowLeftIcon data-icon="inline-start" />
          Back
        </Button>
        <div className="flex items-center gap-3">
          <span className="text-xs text-muted-foreground">A4 · prints light</span>
          <Button size="sm" onClick={() => window.print()}>
            <PrinterIcon data-icon="inline-start" />
            Print / Save as PDF
          </Button>
        </div>
      </div>

      <div className="print-sheet mx-auto mb-8 w-full max-w-[210mm]">
        <header className="flex items-start justify-between gap-8">
          <div>
            <BusinessLogo
              name={businessName}
              logo={business?.logo ?? ''}
              className="print-logo mb-2"
            />
            <p className="print-business">{businessName}</p>
            {business?.address === undefined || business.address === '' ? null : (
              <p className="print-muted print-small">{business.address}</p>
            )}
            {business?.email === undefined || business.email === '' ? null : (
              <p className="print-muted print-small">{business.email}</p>
            )}
          </div>

          <div className="text-right">
            <p className="print-doc-type">Document</p>
            <p className="print-number">{document.title}</p>
            <p className="print-muted print-small">
              {document.scope === 'client' ? 'Client document' : 'Global template'}
            </p>
            <p className="print-muted print-small">Updated {formatDate(document.updated_at)}</p>
          </div>
        </header>

        {client === null ? null : (
          <section className="print-parties">
            <div>
              <p className="print-label">Prepared for</p>
              <p className="print-strong">{recordTitle(client)}</p>
              {client.company === '' ? null : (
                <p className="print-muted print-small">{client.company}</p>
              )}
              {client.email === '' ? null : (
                <p className="print-muted print-small">{client.email}</p>
              )}
            </div>
            <div>
              <p className="print-label">Kind</p>
              <p className="print-small capitalize">{document.kind}</p>
            </div>
          </section>
        )}

        <Markdown className="print-small">{content}</Markdown>

        <PaymentBlock business={business} />

        <footer className="print-footer">
          <p className="print-muted print-small">{document.path} · generated by ob</p>
        </footer>
      </div>
    </div>
  );
};
